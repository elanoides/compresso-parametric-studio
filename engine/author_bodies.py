"""Authoritative Cap-Height bitmaps (TYPE TOOL 5×20 mesh).

body row i → studio row 4+i (Cap-Height).
Accents → rows 1..2; descenders → rows 24..25.
"""

from __future__ import annotations

BODY_H = 20


def R(row: str, n: int) -> list[str]:
    return [row] * n


def H(stem_rows: int, bar_at: int, width: int = 5) -> list[str]:
    """Two side stems + one full bar (H / Н family)."""
    side = "#" + "." * (width - 2) + "#"
    bar = "#" * width
    rows = []
    for i in range(BODY_H):
        rows.append(bar if i == bar_at else side)
    return rows


