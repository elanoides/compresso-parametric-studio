def resolve_bodies() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for ch, rows in BODIES.items():
        if rows is not None:
            out[ch] = list(rows)
    # resolve aliases after bases exist
    for dst, src in _ALIASES.items():
        out[dst] = list(out[src])
    return out


def validate(bodies: dict[str, list[str]]) -> None:
    bad = []
    for ch, rows in bodies.items():
        if len(rows) != BODY_H:
            bad.append((ch, f"len={len(rows)}"))
            continue
        w = len(rows[0])
        if any(len(r) != w for r in rows):
            bad.append((ch, "ragged"))
    if bad:
        raise ValueError(bad)
